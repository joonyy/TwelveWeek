export default function WritingGuide({ step, weekCount = 12 }) {
  const guide = guides[step];
  const text = (value) => value.replaceAll("{weeks}", String(weekCount));
  return (
    <aside className="writing-guide" aria-label={`${guide.label} 작성 안내`}>
      <header>
        <NotebookPen size={16} aria-hidden="true" />
        <strong>작성할 때 떠올릴 생각</strong>
        <span>{guide.source}</span>
      </header>
      <p className="writing-question">{text(guide.question)}</p>
      <ul>
        {guide.points.map((point) => (
          <li key={point}>{text(point)}</li>
        ))}
      </ul>
      {guide.criteria && (
        <ul className="writing-criteria" aria-label="목표의 다섯 조건">
          {guide.criteria.map((criterion) => (
            <li key={criterion}>{criterion}</li>
          ))}
        </ul>
      )}
      {guide.caution && (
        <p className="writing-caution">
          <strong>유의할 점</strong> {text(guide.caution)}
        </p>
      )}
    </aside>
  );
}
